import 'dart:convert';
import 'dart:ui';
import 'package:flutter_test/flutter_test.dart';
import 'package:pocketdesk/core/geometry.dart';
import 'package:pocketdesk/core/pd_crypto.dart';

void main() {
  group('crypto (must match agent/crypto.py)', () {
    test('HKDF RFC5869 test case 1', () {
      final okm = hkdfSha256(List.filled(22, 0x0b), unhex('000102030405060708090a0b0c'), unhex('f0f1f2f3f4f5f6f7f8f9'), 42);
      expect(hex(okm), '3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865');
    });
    test('pairing code parse', () {
      final p = parsePairingCode('abcdef-aaaa-aaaa-aaaa-aaaa');
      expect(p.lookup, 'ABCDEF');
      expect(p.secret.length, 10);
      expect(p.secret, everyElement(0));
      expect(() => parsePairingCode('nope'), throwsFormatException);
      expect(() => parsePairingCode('ABCDEF-1111-AAAA-AAAA-AAAA'), throwsFormatException);
    });
    test('cross-language vector (generated by agent crypto.py)', () {
      // secret = 0123456789 (ASCII bytes); values computed with the Python implementation
      final key = derivePairKey(utf8.encode('0123456789'));
      expect(hex(key), _pyKey);
      const sdp = 'v=0\r\na=fingerprint:sha-256 AA:BB:CC\r\n';
      expect(offerMac(key, 's', 'd', 5, sdp), _pyOffer);
      expect(answerMac(key, 's', 'd', 5, sdp), _pyAnswer);
      expect(claimProof(key, 'ABCDEF', 'Phone'), _pyClaim);
    });
    test('mac binds fingerprint', () {
      final key = derivePairKey(utf8.encode('0123456789'));
      expect(offerMac(key, 's', 'd', 5, 'a=fingerprint:sha-256 AA:BB\r\n') == offerMac(key, 's', 'd', 5, 'a=fingerprint:sha-256 AA:BC\r\n'), false);
      expect(constantTimeEquals('ab', 'ab'), true);
      expect(constantTimeEquals('ab', 'ac'), false);
    });
  });

  group('coordinate mapping', () {
    const view = Size(800, 400);
    test('letterboxed 16:9 video in wide view', () {
      const g = ViewGeometry(view, Size(1920, 1080));
      final r = g.fit;
      expect(r.height, 400);
      expect(r.width, closeTo(711.11, 0.01));
      expect(g.toNormalized(Offset(r.left, 0)), const Offset(0, 0));
      expect(g.toNormalized(Offset(r.right, 400)).dx, closeTo(1, 1e-9));
      expect(g.toNormalized(const Offset(400, 200)), const Offset(0.5, 0.5));
      expect(g.toNormalized(const Offset(0, 0)), const Offset(0, 0)); // black bar clamps
    });
    test('zoom + pan roundtrip', () {
      const g = ViewGeometry(view, Size(1600, 800), zoom: 2, pan: Offset(-300, -100));
      for (final n in [const Offset(0.2, 0.3), const Offset(0.9, 0.1), const Offset(0.5, 0.5)]) {
        final back = g.toNormalized(g.toLocal(n));
        expect(back.dx, closeTo(n.dx, 1e-9));
        expect(back.dy, closeTo(n.dy, 1e-9));
      }
    });
    test('clampPan keeps content covering view', () {
      const g = ViewGeometry(view, Size(1600, 800));
      expect(g.clampPan(const Offset(50, 50), 2), Offset.zero);
      expect(g.clampPan(const Offset(-5000, -5000), 2), const Offset(-800, -400));
    });
    test('trackpad scale', () {
      const g = ViewGeometry(view, Size(1600, 800), zoom: 2);
      expect(g.remotePerScreenPixel(), closeTo(1.0, 1e-9));
    });
  });
}

const _pyKey = '6b82f2982e0fc8803cb924173aa194d678bbd8ea09ed10614b5ccd0074ebbd9a';
const _pyOffer = '45cac67b9534d5a5d43d79b3a8186da21590cc9c3236d8b21f6779d7b445306a';
const _pyAnswer = '5ae8be710fc81b6b73a96a97805e532bbdaeabb789b3a36c3cc6c373d73b678a';
const _pyClaim = '10b9429d1e8c0a57dbc5f8e1b8e54cea24f4825ee7975dfd5898bb62a64734fe';
